; ============================================================
; Сложный уровень, задание 1, п.2: приближённое вычисление sin(x)
; с помощью инструкций SSE (одинарная точность).
;
; Метод: приведение аргумента к [-pi, pi] + ряд Тейлора 7-го порядка:
;     sin(x) ≈ x - x^3/6 + x^5/120 - x^7/5040
;
; Вход:  x  — константа в .rodata
; Выход: y  — результат в .bss (смотреть в отладчике)
; ============================================================

%include 'io64.inc'

section .rodata
    ; ----- аргумент -----
    x:          dd 0.5235988         ; 30° в радианах = pi/6

    ; ----- константы для приведения к [-pi, pi] -----
    two_pi:     dd 6.283185307179586
    inv_two_pi: dd 0.15915494309189535

    ; ----- факториалы -----
    c6:         dd 6.0
    c120:       dd 120.0
    c5040:      dd 5040.0

section .bss
    y:  resd 1                       ; результат

section .text
global main

main:
    mov rbp, rsp; for correct debugging
    ; ---------------------------------------------------------
    ; 1. Приведение x к диапазону [-pi, pi]
    ;    n = round(x / 2pi);  x = x - n * 2pi
    ; ---------------------------------------------------------
    movss   xmm0, [x]                ; xmm0 = x
    movaps  xmm1, xmm0
    mulss   xmm1, [inv_two_pi]       ; xmm1 = x / 2pi
    cvtss2si eax, xmm1               ; eax  = round(x / 2pi)
    cvtsi2ss xmm1, eax               ; xmm1 = (float)n
    mulss   xmm1, [two_pi]           ; xmm1 = n * 2pi
    subss   xmm0, xmm1               ; xmm0 = x - n*2pi  ∈ [-pi, pi]

    ; ---------------------------------------------------------
    ; 2. Степени x: x^2, x^3, x^5, x^7
    ; ---------------------------------------------------------
    movss   xmm1, xmm0
    mulss   xmm1, xmm1               ; xmm1 = x^2
    movss   xmm2, xmm1
    mulss   xmm2, xmm0               ; xmm2 = x^3
    movss   xmm3, xmm2
    mulss   xmm3, xmm1               ; xmm3 = x^5
    movss   xmm4, xmm3
    mulss   xmm4, xmm1               ; xmm4 = x^7

    ; ---------------------------------------------------------
    ; 3. Деление на факториалы
    ; ---------------------------------------------------------
    divss   xmm2, [c6]               ; x^3 / 6
    divss   xmm3, [c120]             ; x^5 / 120
    divss   xmm4, [c5040]            ; x^7 / 5040

    ; ---------------------------------------------------------
    ; 4. Ряд Тейлора: x - x^3/6 + x^5/120 - x^7/5040
    ; ---------------------------------------------------------
    subss   xmm0, xmm2
    addss   xmm0, xmm3
    subss   xmm0, xmm4

    ; ---------------------------------------------------------
    ; 5. Сохранить результат
    ; ---------------------------------------------------------
    movss   [y], xmm0

    ; ---------------------------------------------------------
    ; 6. Корректный выход
    ; ---------------------------------------------------------
    xor     eax, eax
    ret